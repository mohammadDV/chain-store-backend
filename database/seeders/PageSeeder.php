                'title' => 'درباره ما',
                'image' => null,
                'content' => $this->aboutContent(),
                'is_active' => true,
                'show_in_menu' => true,
                'sort_order' => 1,
                'meta_title' => 'درباره ما',
                'meta_description' => 'درباره فروشگاه بوف استور؛ تأمین و فروش کالاهای ورزشی اورجینال با کیفیت و قیمت منصفانه',
            ],
            [
                'slug' => 'complaint',
                'title' => 'ثبت شکایت',
                'image' => null,
                'content' => $this->complaintContent(),
                'is_active' => true,
                'show_in_menu' => true,
                'sort_order' => 2,
                'meta_title' => 'ثبت شکایت',
                'meta_description' => 'ثبت شکایت و درخواست بررسی از پشتیبانی بوف استور',
            ],
            [
                'slug' => 'rules',
                'title' => 'قوانین و مقررات',
                'image' => null,
                'content' => $this->rulesContent(),
                'is_active' => true,
                'show_in_menu' => false,
