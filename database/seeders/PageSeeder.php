<?php

namespace Database\Seeders;

use Domain\Page\Models\Page;
use Domain\Setting\Models\Setting;
use Illuminate\Database\Seeder;

class PageSeeder extends Seeder
{
    public function run(): void
    {
        $this->seedContactSettings();

        foreach ($this->pages() as $page) {
            Page::query()->updateOrCreate(
                ['slug' => $page['slug']],
                $page
            );
        }
    }

    private function seedContactSettings(): void
    {
        $setting = Setting::getInstance();

        $setting->fill([
            'contact_title' => $setting->contact_title ?: 'با ما در  ارتباط باشید',
            'contact_subtitle' => $setting->contact_subtitle ?: 'ما میتوانیم به شما کمک کنیم!',
            'contact_phone' => $setting->contact_phone ?: '021-11111111',
            'contact_phone_hours' => $setting->contact_phone_hours ?: '24/7',
            'contact_address' => $setting->contact_address ?: 'تهران',
            'contact_map_url' => $setting->contact_map_url ?: '/',
            'contact_email' => $setting->contact_email ?: 'Info@boofstore.com',
            'contact_email_hint' => $setting->contact_email_hint ?: 'پیغام خود را به ما ارسال کنید',
        ])->save();
    }

    /**
     * @return list<array<string, mixed>>
     */
    private function pages(): array
    {
        return [
            [
